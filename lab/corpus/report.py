#!/usr/bin/env python3
"""Summarise layout slop in the corpus from detect.mjs output.

Usage:
  node lab/tools/detect.mjs lab/corpus/sites --out lab/corpus/detect.json
  python3 lab/corpus/report.py          → lab/corpus/layout-slop.md

Rates are shares of pages showing each pattern: overall, per model and per kind of site. Stats rows are not
counted on dashboards, where a row of numbers is the point. Standard library only.
"""
import json
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
NAMES = {
    "roundedEverything": "Rounded boxes everywhere",
    "gradient": "Decorative gradient (background or text)",
    "threeCardRow": "Row of three cards",
    "pillBadge": "Pill badge above the headline",
    "emojiIcons": "Emoji used as icons",
    "statsRow": "Row of big numbers (not on dashboards)",
    "centeredHero": "Centered hero headline",
    "uniformSpacing": "Same padding on every section",
    "purpleAccent": "Indigo, violet or purple main button",
}


def main():
    results = [r for r in json.loads((HERE / "detect.json").read_text()) if "patterns" in r]
    manifest = json.loads((HERE / "manifest.json").read_text())
    rows = []
    for r in results:
        parts = Path(r["file"]).parts
        model, name = parts[-2], parts[-1]
        kind = manifest[name[:2]]["kind"]
        hits = {k for k, v in r["patterns"].items() if v["hit"]}
        if kind == "dashboard":
            hits.discard("statsRow")
        rows.append({"model": model, "kind": kind, "hits": hits, "fonts": r["fonts"]})

    def rate(subset, key):
        n = len(subset)
        return f"{sum(key in x['hits'] for x in subset) / n:.0%}" if n else "–"

    models = sorted({x["model"] for x in rows})
    kinds = list(dict.fromkeys(m["kind"] for m in manifest.values()))
    order = sorted(NAMES, key=lambda k: -sum(k in x["hits"] for x in rows))

    out = ["# Layout slop in AI-built sites", "",
           f"{len(rows)} pages: the 30 generic briefs in `manifest.json`, built by {', '.join(models)} with no skills "
           "and no personal settings. Measured on the rendered page by `lab/tools/detect.mjs` (calibrated on "
           "`layout/tests/fixtures/`). Generated by `report.py`; don't edit by hand.", "",
           "## By model", "", "| Pattern | All | " + " | ".join(m.replace("claude-", "") for m in models) + " |",
           "|---|---|" + "---|" * len(models)]
    for k in order:
        out.append(f"| {NAMES[k]} | {rate(rows, k)} | " +
                   " | ".join(rate([x for x in rows if x["model"] == m], k) for m in models) + " |")
    out += ["", "## By kind of site", "", "| Pattern | " + " | ".join(kinds) + " |", "|---|" + "---|" * len(kinds)]
    for k in order:
        out.append(f"| {NAMES[k]} | " + " | ".join(rate([x for x in rows if x["kind"] == kd], k) for kd in kinds) + " |")

    per_page = [len(x["hits"]) for x in rows]
    out += ["", "## Per page", "",
            f"- Average patterns per page: {sum(per_page) / len(per_page):.1f} of {len(NAMES)}.",
            f"- Pages with none: {sum(n == 0 for n in per_page)} of {len(rows)}.",
            f"- Pages with four or more: {sum(n >= 4 for n in per_page)} of {len(rows)}."]
    counts = defaultdict(int)
    for x in rows:
        counts[x["fonts"]["heading"]] += 1
    top = sorted(counts.items(), key=lambda kv: -kv[1])[:8]
    out += ["", "## Heading fonts", "", "Computed `font-family` of the main heading, first name only.", "",
            "| Font | Pages |", "|---|---|"] + [f"| {f} | {n} |" for f, n in top]
    out += ["", "## Limits", "",
            "- One company's models only: other providers weren't available when this ran.",
            "- Each check is a heuristic on computed styles. Spot-checked against screenshots; see "
            "`layout/tests/fixtures/` for what each one must and mustn't catch.",
            "- A pattern isn't wrong in itself. It's slop when nearly every page reaches for it regardless of brief."]
    (HERE / "layout-slop.md").write_text("\n".join(out) + "\n")
    summary = {"pages": len(rows), "models": models,
               "rates": {k: sum(k in x["hits"] for x in rows) / len(rows) for k in order},
               "by_model": {m: {k: sum(k in x["hits"] for x in rows if x["model"] == m) /
                                max(1, sum(x["model"] == m for x in rows)) for k in order} for m in models}}
    (HERE / "layout-slop.json").write_text(json.dumps(summary, indent=2) + "\n")
    print("\n".join(out[:20]))


if __name__ == "__main__":
    main()
